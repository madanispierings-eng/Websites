#!/usr/bin/env bash
# Combines all migrations and the seed into supabase/setup.sql: one file to paste into the Supabase SQL Editor
# for a fresh project. Re-run after adding a migration (tests/setup-sql.test.ts checks it is up to date).
set -euo pipefail
cd "$(dirname "$0")/.."
{
  echo "-- Medivo database setup: all migrations plus the course catalogue, for a NEW Supabase project."
  echo "-- Generated by scripts/build-setup-sql.sh. Do not edit by hand; run it once in the SQL Editor."
  for f in supabase/migrations/*.sql supabase/seed.sql; do
    echo
    echo "-- ===== $f ====="
    cat "$f"
  done
} > supabase/setup.sql
